//! Repository automation: `cargo xtask <task>`.
//!
//! Tasks:
//!
//! - `gen-types` writes the TypeScript wire types in `packages/types/src` from the Rust types
//!   (via `ts-rs`). Never edit those files by hand.
//! - `gen-types --check` regenerates into a temporary directory and fails if
//!   `packages/types/src` differs (used by CI).
//! - `build-wasm` builds `hardless-wasm` for the browser and writes the JavaScript glue
//!   to `packages/shim-web/wasm` (needs `wasm-bindgen-cli` matching the `wasm-bindgen`
//!   version in Cargo.lock).
//! - `docs` writes the generated reference pages in `docs/reference/` (devices, faults,
//!   ESC/POS commands, HTTP dialects, MCP tools) and `llms.txt` (FR-46, FR-51), from the code.
//!   `docs --check` fails if any is out of date, or if a page in `docs/` is missing from
//!   `llms.txt` (CI).
//! - `licenses` writes `crates/hardless-cli/THIRD_PARTY_LICENSES.txt`, the third-party notices
//!   the binary and Docker image ship (NFR-14), from cargo-about, the Go Mono font licence and
//!   the built dashboard's notices, and `packages/shim-web/THIRD_PARTY_LICENSES.txt` for the
//!   WebAssembly engine. `licenses --check` fails if either file is out of date (CI).

mod docs;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use hardless_core as core;
use hardless_escpos as escpos;
use ts_rs::{Config, TS};

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args
        .iter()
        .map(String::as_str)
        .collect::<Vec<_>>()
        .as_slice()
    {
        ["gen-types"] => gen_types(false),
        ["gen-types", "--check"] => gen_types(true),
        ["build-wasm"] => build_wasm(),
        ["licenses"] => licenses(false),
        ["licenses", "--check"] => licenses(true),
        ["docs"] => gen_docs(false),
        ["docs", "--check"] => gen_docs(true),
        _ => Err(USAGE.to_owned()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("xtask: {message}");
            ExitCode::FAILURE
        }
    }
}

const USAGE: &str =
    "usage: cargo xtask gen-types [--check] | build-wasm | licenses [--check] | docs [--check]";

/// Writes the generated docs and `llms.txt`, or with `check` fails if they are stale.
fn gen_docs(check: bool) -> Result<(), String> {
    let root = workspace_root();
    let generated = docs::generated();
    let mut files: Vec<(String, String)> = generated
        .iter()
        .map(|(path, text)| ((*path).to_owned(), text.clone()))
        .collect();
    files.push(("llms.txt".to_owned(), docs::llms_txt(&root, &generated)?));
    let unlisted = docs::unlisted(&root);
    if !unlisted.is_empty() {
        return Err(format!(
            "add these pages to PAGES in xtask/src/docs.rs so llms.txt lists them: {}",
            unlisted.join(", ")
        ));
    }
    let mut stale = Vec::new();
    for (path, text) in &files {
        let full = root.join(path);
        if check {
            let current = fs::read_to_string(&full)
                .unwrap_or_default()
                .replace("\r\n", "\n");
            if current != *text {
                stale.push(path.clone());
            }
        } else {
            if let Some(dir) = full.parent() {
                fs::create_dir_all(dir).map_err(|e| format!("creating {}: {e}", dir.display()))?;
            }
            fs::write(&full, text).map_err(|e| format!("writing {path}: {e}"))?;
        }
    }
    if !stale.is_empty() {
        return Err(format!(
            "out of date: {}. Run `cargo xtask docs` and commit the result.",
            stale.join(", ")
        ));
    }
    println!(
        "{} {} files",
        if check { "checked" } else { "wrote" },
        files.len()
    );
    Ok(())
}

const HEADER: &str =
    "// Generated by `cargo xtask gen-types` from the Rust wire types. Do not edit.\n";

fn workspace_root() -> PathBuf {
    // xtask/ is one level below the workspace root.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_default()
}

/// Exports every wire type (and, transitively, the types it uses) into `dir`.
fn export_all(dir: &Path) -> Result<(), String> {
    let cfg = Config::new().with_out_dir(dir).with_large_int("number");
    macro_rules! export {
        ($($ty:ty),* $(,)?) => {
            $( <$ty as TS>::export_all(&cfg)
                .map_err(|e| format!("exporting {}: {e}", stringify!($ty)))?; )*
        };
    }
    export!(
        core::BusEvent,
        core::DeviceSummary,
        core::EventRecord,
        core::Job,
        core::ControlCommand,
        core::FaultSpec,
        core::LogEntry,
        core::Direction,
        core::PeripheralSignal,
        core::Scenario,
        core::ScenarioReport,
        escpos::Node,
        core::bridge::ClientFrame,
        core::bridge::ServerFrame,
        core::bridge::SerialSignals,
    );
    Ok(())
}

/// Lists every `.ts` file under `dir`, recursively.
fn ts_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("reading {}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            ts_files(&path, out)?;
        } else if path.extension().and_then(|e| e.to_str()) == Some("ts") {
            out.push(path);
        }
    }
    Ok(())
}

/// Rewrites a ts-rs import line so it works under ESM (`moduleResolution: NodeNext`): files
/// are flattened into one directory and imports get a `.js` extension.
fn fix_import(line: &str) -> String {
    let Some((head, spec)) = line.split_once(" from \"") else {
        return line.to_owned();
    };
    let spec = spec.trim_end_matches(['"', ';']);
    let module = spec.rsplit('/').next().unwrap_or(spec);
    format!("{head} from \"./{module}.js\";")
}

/// Reads every `.ts` file ts-rs wrote, flattens them into one directory, normalises line
/// endings, and adds the header and an `index.ts` that re-exports everything.
fn collect(dir: &Path) -> Result<BTreeMap<String, String>, String> {
    let mut paths = Vec::new();
    ts_files(dir, &mut paths)?;
    let mut files = BTreeMap::new();
    for path in paths {
        let Some(name) = path.file_name().and_then(|n| n.to_str()).map(str::to_owned) else {
            continue;
        };
        if name == "index.ts" {
            continue;
        }
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let mut body = String::new();
        for line in text.replace("\r\n", "\n").lines() {
            // Drop ts-rs's own banner; ours says how to regenerate.
            if line.starts_with("// This file was generated by") {
                continue;
            }
            if line.starts_with("import ") {
                body.push_str(&fix_import(line));
            } else {
                body.push_str(line);
            }
            body.push('\n');
        }
        if files
            .insert(name.clone(), format!("{HEADER}{}", body.trim_start()))
            .is_some()
        {
            return Err(format!("two generated types are both named {name}"));
        }
    }
    let mut index = String::from(HEADER);
    for name in files.keys() {
        let module = name.trim_end_matches(".ts");
        index.push_str(&format!("export type * from \"./{module}.js\";\n"));
    }
    files.insert("index.ts".to_owned(), index);
    Ok(files)
}

fn gen_types(check: bool) -> Result<(), String> {
    let target = workspace_root().join("packages").join("types").join("src");
    let scratch = std::env::temp_dir().join(format!("hardless-gen-types-{}", std::process::id()));
    let _ = fs::remove_dir_all(&scratch);
    fs::create_dir_all(&scratch).map_err(|e| e.to_string())?;
    let result = export_all(&scratch).and_then(|()| collect(&scratch));
    let _ = fs::remove_dir_all(&scratch);
    let generated = result?;

    let existing = if target.exists() {
        read_ts(&target)?
    } else {
        BTreeMap::new()
    };
    if check {
        if existing == generated {
            println!("packages/types is up to date ({} files)", generated.len());
            return Ok(());
        }
        let mut stale: Vec<&str> = generated
            .iter()
            .filter(|(name, text)| existing.get(*name) != Some(text))
            .map(|(name, _)| name.as_str())
            .collect();
        stale.extend(
            existing
                .keys()
                .filter(|n| !generated.contains_key(*n))
                .map(String::as_str),
        );
        return Err(format!(
            "packages/types is stale ({}). Run `cargo xtask gen-types` and commit the result.",
            stale.join(", ")
        ));
    }

    fs::create_dir_all(&target).map_err(|e| e.to_string())?;
    for name in existing.keys().filter(|n| !generated.contains_key(*n)) {
        fs::remove_file(target.join(name)).map_err(|e| e.to_string())?;
    }
    for (name, text) in &generated {
        fs::write(target.join(name), text).map_err(|e| e.to_string())?;
    }
    println!("wrote {} files to packages/types/src", generated.len());
    Ok(())
}

fn read_ts(dir: &Path) -> Result<BTreeMap<String, String>, String> {
    let mut files = BTreeMap::new();
    for entry in fs::read_dir(dir).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().and_then(|e| e.to_str()) != Some("ts") {
            continue;
        }
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default()
            .to_owned();
        let text = fs::read_to_string(&path).map_err(|e| e.to_string())?;
        files.insert(name, text.replace("\r\n", "\n"));
    }
    Ok(files)
}

fn run(command: &mut std::process::Command) -> Result<(), String> {
    let status = command
        .status()
        .map_err(|e| format!("cannot run {:?}: {e}", command.get_program()))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("{:?} failed with {status}", command.get_program()))
    }
}

/// Builds the engine for the browser (standalone mode, FR-15).
fn build_wasm() -> Result<(), String> {
    let root = workspace_root();
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    run(std::process::Command::new(cargo).current_dir(&root).args([
        "build",
        "-p",
        "hardless-wasm",
        "--target",
        "wasm32-unknown-unknown",
        "--release",
    ]))?;
    let wasm = root.join("target/wasm32-unknown-unknown/release/hardless_wasm.wasm");
    let out = root.join("packages/shim-web/wasm");
    run(std::process::Command::new("wasm-bindgen")
        .current_dir(&root)
        .arg("--target")
        .arg("web")
        .arg("--out-dir")
        .arg(&out)
        .arg(&wasm))
    .map_err(|e| format!("{e}; install it with: cargo install wasm-bindgen-cli --version <the wasm-bindgen version in Cargo.lock> --locked"))?;
    let size = fs::metadata(out.join("hardless_wasm_bg.wasm"))
        .map(|m| m.len())
        .unwrap_or_default();
    println!(
        "wrote packages/shim-web/wasm ({} KiB of WebAssembly)",
        size / 1024
    );
    Ok(())
}

/// Where the combined notices live; the `hardless` binary embeds this file.
const LICENSES_FILE: &str = "crates/hardless-cli/THIRD_PARTY_LICENSES.txt";

/// The notices for the WebAssembly engine, shipped in `@hardless/shim-web`.
const SHIM_LICENSES_FILE: &str = "packages/shim-web/THIRD_PARTY_LICENSES.txt";

/// The cargo-about report for one crate, offline so it depends only on Cargo.lock. `target`
/// overrides the platforms in `about.toml`.
fn cargo_about(root: &Path, manifest: &str, target: Option<&str>) -> Result<String, String> {
    let mut command = std::process::Command::new("cargo");
    command.current_dir(root).args([
        "about",
        "generate",
        "--frozen",
        "-c",
        "about.toml",
        "-m",
        manifest,
    ]);
    if let Some(target) = target {
        command.args(["--target", target]);
    }
    let output = command
        .arg("about.hbs")
        .output()
        .map_err(|e| format!("cannot run cargo-about: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "cargo about failed (install it with: cargo install cargo-about --version 0.9.2 --locked --features cli):\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| e.to_string())
}

/// A notices section heading.
fn part(title: &str) -> String {
    format!("{}\n# {title}\n{}\n", "#".repeat(78), "#".repeat(78))
}

/// Writes `text` to `file`, or with `check` fails if the committed file differs.
fn write_or_check(root: &Path, file: &str, text: &str, check: bool) -> Result<(), String> {
    let path = root.join(file);
    if check {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current.replace("\r\n", "\n") != text {
            return Err(format!(
                "{file} is out of date. Run `cargo xtask licenses` and commit the result."
            ));
        }
        println!("{file} is up to date");
    } else {
        fs::write(&path, text).map_err(|e| format!("writing {file}: {e}"))?;
        println!("wrote {file} ({} KiB)", text.len() / 1024);
    }
    Ok(())
}

/// Writes the third-party notices (NFR-14): for the binary and the Docker image, the Rust
/// crates (cargo-about), the Go Mono font and the dashboard's bundled packages; for
/// `@hardless/shim-web`, the Rust crates compiled into its WebAssembly engine. With `check`,
/// fails if a committed file is out of date instead.
fn licenses(check: bool) -> Result<(), String> {
    let root = workspace_root();
    let rust = cargo_about(&root, "crates/hardless-cli/Cargo.toml", None)?;
    let font = fs::read_to_string(root.join("crates/hardless-render/fonts/LICENSE"))
        .map_err(|e| format!("reading the Go Mono font licence: {e}"))?;
    let dashboard =
        fs::read_to_string(root.join("packages/dashboard/dist/THIRD_PARTY_LICENSES.txt")).map_err(
            |e| format!("{e}: build the dashboard first (pnpm --filter @hardless/dashboard build)"),
        )?;

    let text = [
        "Third-party software in the `hardless` binary and the hardless/hardless image.\n\
         Generated by `cargo xtask licenses`; do not edit. Print it with `hardless licenses`.\n\n\
         Hardless itself is licensed under Apache-2.0 (the LICENSE file in the repository).\n"
            .to_owned(),
        part("Part 1: Rust crates compiled into the binary"),
        rust.trim().to_owned() + "\n",
        part("Part 2: Go Mono font (embedded for PNG receipts)"),
        font.trim().to_owned() + "\n",
        part("Part 3: The dashboard (embedded web app)"),
        dashboard.trim().to_owned() + "\n",
    ]
    .join("\n")
    .replace("\r\n", "\n");
    write_or_check(&root, LICENSES_FILE, &text, check)?;

    let wasm = cargo_about(
        &root,
        "crates/hardless-wasm/Cargo.toml",
        Some("wasm32-unknown-unknown"),
    )?;
    let text = [
        "Third-party software in the Hardless WebAssembly engine (wasm/ in @hardless/shim-web).\n\
         Generated by `cargo xtask licenses`; do not edit.\n\n\
         Hardless itself is licensed under Apache-2.0 (the LICENSE file in this package).\n"
            .to_owned(),
        part("Rust crates compiled into the WebAssembly engine"),
        wasm.trim().to_owned() + "\n",
    ]
    .join("\n")
    .replace("\r\n", "\n");
    write_or_check(&root, SHIM_LICENSES_FILE, &text, check)
}
